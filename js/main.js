function applyLanguage(lang) {
  const pack = translations[lang] || translations.bs;
  document.documentElement.lang = lang === "en" ? "en" : "bs";
  document.title = pack["meta.title"];
  document.querySelector('meta[name="description"]').setAttribute("content", pack["meta.description"]);
  const ogTitle = document.querySelector('meta[property="og:title"]');
  const ogDescription = document.querySelector('meta[property="og:description"]');
  const ogLocale = document.querySelector('meta[property="og:locale"]');
  const twTitle = document.querySelector('meta[name="twitter:title"]');
  const twDescription = document.querySelector('meta[name="twitter:description"]');
  if (ogTitle) ogTitle.setAttribute("content", pack["meta.title"]);
  if (ogDescription) ogDescription.setAttribute("content", pack["meta.description"]);
  if (ogLocale) ogLocale.setAttribute("content", lang === "en" ? "en_US" : "bs_BA");
  if (twTitle) twTitle.setAttribute("content", pack["meta.title"]);
  if (twDescription) twDescription.setAttribute("content", pack["meta.description"]);

  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const value = pack[node.dataset.i18n];
    if (typeof value === "string") node.textContent = value;
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
    const value = pack[node.dataset.i18nPlaceholder];
    if (typeof value === "string") node.placeholder = value;
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((node) => {
    const value = pack[node.dataset.i18nAria];
    if (typeof value === "string") node.setAttribute("aria-label", value);
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((node) => {
    const value = pack[node.dataset.i18nAlt];
    if (typeof value === "string") node.alt = value;
  });

  document.querySelectorAll("[data-lang]").forEach((button) => {
    button.setAttribute("aria-pressed", String(button.dataset.lang === (lang === "en" ? "en" : "bs")));
  });

  try {
    localStorage.setItem("gurman-lang", lang === "en" ? "en" : "bs");
  } catch {
    /* private browsing */
  }
}

